# ── Normalisation ─────────────────────────────────────────────────────────────

def _normaliser(texte: str) -> str:
    """Majuscules, sans accents, sans ponctuation — pour la comparaison fuzzy."""
    if not texte:
        return ""
    t = unicodedata.normalize("NFD", str(texte).upper())
    t = "".join(c for c in t if unicodedata.category(c) != "Mn")
    t = re.sub(r"[^\w\s]", " ", t)
    return " ".join(t.split())


# ── Calcul du numéro TVA français depuis le SIREN ─────────────────────────────

def _siren_vers_tva(siren: str) -> str:
    """Formule officielle INSEE : clé = (12 + 3 × (SIREN mod 97)) mod 97"""
    n = int(str(siren).strip())
    cle = (12 + 3 * (n % 97)) % 97
    return f"FR{cle:02d}{siren}"


# ── Entités à exclure de la recherche SIREN ───────────────────────────────────

PATTERNS_EXCLUSION = [
    "NATURAL PERSON", "PERSONNE PRIV", "PRIVATPERSON",
    "ART. 38(7)", "ART 38",
]
ENTITES_SUPRA = [
    "COUNCIL OF EUROPE", "CONSEIL DE L'EUROPE",
    "EUROPEAN SPACE AGENCY", "AGENCE SPATIALE EUROPEENNE",
    "UNITED NATIONS", "NATIONS UNIES",
    "ORGANIZATION FOR ECONOMIC", "ORGANISATION DE COOPERATION",
    "REPUBLIQUE FRANCAISE", "FRENCH REPUBLIC",
]

def _est_exclu(nom: str) -> bool:
    nom_up = str(nom).upper()
    for pat in PATTERNS_EXCLUSION + ENTITES_SUPRA:
        if pat in nom_up:
            return True
    return False


# ── Suppression des suffixes juridiques ───────────────────────────────────────

SUFFIXES_REGEX = [
    r"\bS\.?A\.?S\.?\b", r"\bS\.?A\.?R\.?L\.?\b", r"\bE\.?U\.?R\.?L\.?\b",
    r"\bS\.?N\.?C\.?\b",  r"\bS\.?C\.?A\.?\b",    r"\bS\.?C\.?S\.?\b",
    r"\bS\.?C\.?O\.?P\.?\b", r"\bS\.?C\.?I\.?C\.?\b",
    r"\bG\.?I\.?E\.?\b",  r"\bG\.?I\.?P\.?\b",
    r"\bE\.?P\.?I\.?C\.?\b", r"\bE\.?P\.?A\.?\b",
    r"\bASSOCIATION\b",   r"\bASSOC\.?\b",
    r"\bFONDATION\b",     r"\bFOND\.?\b",
    r"\bCOMMUNE\b",       r"\bSTe?\.?\b",
    r"\bLTD\.?\b",        r"\bGMBH\b",
]

def _supprimer_suffixes(nom: str) -> str:
    result = str(nom).upper()
    for pat in SUFFIXES_REGEX:
        result = re.sub(pat, "", result, flags=re.IGNORECASE)
    result = re.sub(r"\s+", " ", result).strip().strip("-").strip(",").strip()
    return result


# ── Extraction des mots clés ──────────────────────────────────────────────────

STOP_WORDS = {
    "DE", "DU", "DES", "LE", "LA", "LES", "ET", "EN", "AU", "AUX",
    "L", "D", "UN", "UNE", "POUR", "PAR", "SUR", "DANS", "A",
    "THE", "OF", "AND", "FOR", "IN", "TO", "DI", "DEL",
}

def _extraire_mots_cles(nom: str, n: int = 4) -> str:
    mots = re.sub(r"[^\w\s]", " ", str(nom).upper()).split()
    significatifs = [m for m in mots if m not in STOP_WORDS and len(m) > 1]
    return " ".join(significatifs[:n])


# ── Génération des 9 requêtes (multi-stratégies) ──────────────────────────────

def _generer_requetes(nom_brut: str, ville: str = None, cp: str = None) -> list:
    nom = str(nom_brut).strip()
    requetes = []

    requetes.append({"query": nom, "cp": cp, "strategie": "1_NOM_COMPLET_CP"})

    if cp:
        requetes.append({"query": nom, "cp": None, "strategie": "2_NOM_COMPLET"})

    if "*" in nom:
        parties = [p.strip() for p in nom.split("*") if p.strip()]
        nom_principal = max(parties, key=len)
        if nom_principal.upper() != nom.upper():
            requetes.append({"query": nom_principal, "cp": cp, "strategie": "3_NOM_PRINCIPAL"})

    if "*" in nom:
        parties = [p.strip() for p in nom.split("*") if p.strip()]
        sigle = min(parties, key=len)
        if len(sigle) >= 2 and sigle.upper() != nom.upper():
            requetes.append({"query": sigle, "cp": cp, "strategie": "4_SIGLE"})

    sans_suf = _supprimer_suffixes(nom)
    if sans_suf and len(sans_suf) > 4 and sans_suf.upper() != nom.upper():
        requetes.append({"query": sans_suf, "cp": cp, "strategie": "5_SANS_SUFFIXE"})

    mots_cles = _extraire_mots_cles(nom, n=4)
    if mots_cles and len(mots_cles) > 5:
        if not any(r["query"].upper().strip() == mots_cles for r in requetes):
            requetes.append({"query": mots_cles, "cp": cp, "strategie": "6_MOTS_CLES"})

    nom_norm = _normaliser(nom)
    if nom_norm and not any(r["query"].upper() == nom_norm for r in requetes):
        requetes.append({"query": nom_norm, "cp": cp, "strategie": "7_NOM_NORMALISE"})

    if len(nom) > 45:
        tronque = nom[:42].rsplit(" ", 1)[0]
        if len(tronque) > 10:
            requetes.append({"query": tronque, "cp": None, "strategie": "8_NOM_TRONQUE"})

    if ville and str(ville).strip():
        premiers = _extraire_mots_cles(nom, n=2)
        if premiers:
            requetes.append({"query": f"{premiers} {str(ville).strip()}",
                             "cp": None, "strategie": "9_NOM_VILLE"})

    vus, dedup = set(), []
    for r in requetes:
        cle = (r["query"].strip().lower(), r.get("cp"))
        if cle not in vus and r["query"].strip():
            vus.add(cle)
            dedup.append(r)
    return dedup


