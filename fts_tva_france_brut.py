# SCORING V2 — 5 critères combinés
# ══════════════════════════════════════════════════════════════════════════════

def _scorer(ref_norm: str, api_norm: str, ref_ville: str, ref_cp: str,
            api_result: dict) -> tuple:
    """
    Calcule un score combiné (0-100) et retourne (score, audit_lisible).

    Critères appliqués dans l'ordre :

    ① Similarité textuelle
       • token_sort_ratio  : robuste aux permutations de mots
         ex. 'SOLIDARITES INTERNATIONAL' ≡ 'INTERNATIONAL SOLIDARITES' → 100
       • token_set_ratio   : gère les inclusions partielles
         ex. 'ACF' dans 'ACTION CONTRE LA FAIM ACF' → score élevé
       • partial_ratio     : conditionnel — uniquement si ratio longueur ≥ 0.60
         Garde : évite que 'PARIS' (5 cars) matche 'CLUB SPORTIF PARIS NORD' (20 cars)

    ② Ratio de longueur
       Si les deux noms ont des longueurs très différentes (ratio < 0.60) :
       → partial_ratio ignoré + pénalité −10% sur le score textuel
       Raison : un nom très court trouvé dans un nom très long = faux positif probable

    ③ État administratif (champ 'etat_administratif' dans la réponse API)
       • 'A' (actif)  → aucun impact
       • 'C' (cessé)  → pénalité −35% (entreprise radiée, SIREN fermé)
       Raison : accepter le SIREN d'une entreprise fermée crée une TVA invalide

    ④ Validation ville
       Compare la ville du FTS avec 'siege.libelle_commune' de l'API
       • Similarité ≥ 80% → bonus +5
       • Similarité < 35% et score < 95 → malus −7%

    ⑤ Validation département
       Compare les 2 premiers chiffres du code postal FTS vs code postal API
       • Même département → bonus +3
       • Département différent et score < 93 → malus −4%
    """
    if not api_norm:
        return 0, "api_nom_vide"

    audit = []

    # ── ① Similarité textuelle ─────────────────────────────────────────────────
    s_sort = fuzz.token_sort_ratio(ref_norm, api_norm)
    s_set  = fuzz.token_set_ratio(ref_norm, api_norm)
    audit.append(f"sort={s_sort}")
    audit.append(f"set={s_set}")

    # ── ② Ratio de longueur + partial_ratio conditionnel ─────────────────────
    len_ref = max(len(ref_norm.replace(" ", "")), 1)
    len_api = max(len(api_norm.replace(" ", "")), 1)
    ratio_lon = min(len_ref, len_api) / max(len_ref, len_api)

    if ratio_lon >= 0.60:
        # Noms de longueur comparable → partial_ratio fiable
        s_partial = fuzz.partial_ratio(ref_norm, api_norm)
        score = max(s_sort, int(s_set * 0.97), int(s_partial * 0.88))
        audit.append(f"partial={s_partial}→pondéré={int(s_partial*0.88)}")
    else:
        # Grande différence de longueur → partial_ratio non fiable → ignoré + pénalité
        score = int(max(s_sort, int(s_set * 0.97)) * 0.90)
        audit.append(f"partial=ignoré(ratio={ratio_lon:.2f},-10%)")

    # ── ③ État administratif ──────────────────────────────────────────────────
    etat = (api_result.get("etat_administratif") or "").strip().upper()
    if etat == "C":
        score = int(score * 0.65)
        audit.append("RADIÉE(-35%)")
    elif etat == "A":
        audit.append("active✓")
    else:
        audit.append(f"état={etat or '?'}")

    # ── ④ Validation ville ────────────────────────────────────────────────────
    siege       = api_result.get("siege") or {}
    api_cp_raw  = str(siege.get("code_postal", "") or "").strip()
    api_commune = _normaliser(siege.get("libelle_commune", "") or "")

    if ref_ville and api_commune:
        sim_v = fuzz.token_sort_ratio(_normaliser(ref_ville), api_commune)
        if sim_v >= 80:
            score = min(100, score + 5)
            audit.append(f"ville≈+5({api_commune})")
        elif sim_v < 35 and score < 95:
            score = max(0, int(score * 0.93))
            audit.append(f"ville≠-7%({api_commune})")

    # ── ⑤ Validation département ─────────────────────────────────────────────
    api_dept = api_cp_raw[:2] if len(api_cp_raw) >= 2 else ""
    ref_dept = ref_cp[:2]     if ref_cp and len(ref_cp) >= 2 else ""

    if ref_dept and api_dept:
        if ref_dept == api_dept:
            score = min(100, score + 3)
            audit.append(f"dept={ref_dept}+3")
        elif score < 93:
            score = max(0, int(score * 0.96))
            audit.append(f"dept≠({ref_dept}≠{api_dept})-4%")

    return min(100, max(0, score)), " | ".join(audit)


# ── Appel API avec scoring v2 ─────────────────────────────────────────────────

def _appeler_api(query: str, cp: str, nom_reference: str, ville_reference: str,
                 session: requests.Session) -> dict | None:
    """
    Interroge l'API et retourne le meilleur résultat scoré sur 5 critères.
    Retourne None si aucun résultat ou erreur réseau.
    """
    params = {"q": query, "page": 1, "per_page": MAX_PAR_REQUETE}
    if cp and str(cp).strip():
        dept = str(cp).strip()
        dept = dept[:3] if dept[:2] in ("97", "98") else dept[:2]
        if dept.isdigit():
            params["departement"] = dept

    try:
        time.sleep(DELAI_API)
        r = session.get(API_URL, params=params, timeout=12)
        r.raise_for_status()
        resultats = r.json().get("results", [])
    except Exception:
        return None

    if not resultats:
        return None

    ref_norm  = _normaliser(nom_reference)
    ref_ville = _normaliser(ville_reference or "")
    meilleur  = None
    meilleur_score = -1

    for res in resultats:
        siren = str(res.get("siren", "")).strip()
        if not siren:
            continue

        # Tous les noms disponibles pour ce SIREN
        noms_candidats = [res.get("nom_complet", "")]
        for champ in ["nom_raison_sociale", "sigle"]:
            val = res.get(champ, "")
            if val:
                noms_candidats.append(val)

        for nom_api in noms_candidats:
            if not nom_api:
                continue
            api_norm = _normaliser(nom_api)
            score, detail = _scorer(ref_norm, api_norm, ref_ville, cp, res)

            if score > meilleur_score:
                meilleur_score = score
                meilleur = {
                    "siren":   siren,
                    "nom_api": nom_api,
                    "score":   score,
                    "detail":  detail,
                }

    if meilleur and meilleur["siren"]:
        meilleur["tva"] = _siren_vers_tva(meilleur["siren"])

    return meilleur


# ── Moteur principal : 9 stratégies en cascade ────────────────────────────────

def rechercher_tva(nom_brut: str, ville: str, cp: str,
                   session: requests.Session, seuil: int) -> dict:
    """
    Tente de retrouver la TVA française d'un bénéficiaire via 9 stratégies.
    S'arrête à la première stratégie dont le score v2 ≥ seuil.
    """
    if _est_exclu(nom_brut):
        return {"statut": "EXCLU", "strategie": "", "siren": "",
                "tva": "", "nom_api": "", "score": 0, "detail": ""}

    requetes = _generer_requetes(nom_brut, ville, cp)
    meilleur_global = None

    for req in requetes:
        res = _appeler_api(req["query"], req["cp"], nom_brut, ville, session)
        if res:
            if meilleur_global is None or res["score"] > meilleur_global["score"]:
                meilleur_global = {**res, "strategie": req["strategie"]}
            if res["score"] >= seuil:
                return {
                    "statut":    "TROUVE",
                    "strategie": req["strategie"],
                    "siren":     res["siren"],
                    "tva":       res["tva"],
                    "nom_api":   res["nom_api"],
                    "score":     res["score"],
                    "detail":    res.get("detail", ""),
                }

    return {
        "statut":    "NON_TROUVE",
        "strategie": meilleur_global.get("strategie", "") if meilleur_global else "",
        "siren":     "",
        "tva":       "",
        "nom_api":   meilleur_global.get("nom_api", "") if meilleur_global else "",
        "score":     meilleur_global.get("score", 0)    if meilleur_global else 0,
        "detail":    meilleur_global.get("detail", "")  if meilleur_global else "",
    }


