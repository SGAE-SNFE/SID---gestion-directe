def detecter_colonnes(df: pd.DataFrame) -> dict:
    def chercher(*mots_cles):
        for mot in mots_cles:
            for c in df.columns:
                if mot.lower() in c.lower():
                    return c
        return None

    cols = {
        "tva":   chercher("vat number", "vat_number", "tva", "numero tva"),
        "nom":   chercher("name of beneficiary", "beneficiary name", "nom benefi", "nom_benef"),
        "pays":  chercher("beneficiary country", "country", "pays"),
        "cp":    chercher("postal code", "code postal", "zip", "postcode"),
        "ville": chercher("city", "ville", "locality", "localite"),
    }

    manquantes = [k for k in ("tva", "nom", "pays") if cols[k] is None]
    if manquantes:
        raise ValueError(
            f"❌ Colonnes obligatoires introuvables : {manquantes}\n"
            f"   Colonnes disponibles : {list(df.columns)}"
        )

    print("📌 Colonnes détectées :")
    for k, v in cols.items():
        print(f"   {'✅' if v else '⚠️ '} {k:8s} → {v or 'non trouvé (optionnel)'}")
    return cols


def enrichir_france(df: pd.DataFrame, colonnes: dict, seuil: int = SEUIL_SCORE) -> tuple:
    col_tva   = colonnes["tva"]
    col_nom   = colonnes["nom"]
    col_pays  = colonnes["pays"]
    col_cp    = colonnes.get("cp")
    col_ville = colonnes.get("ville")

    mask_fr = df[col_pays].str.strip().str.lower().isin(["france", "fr"])
    print(f"🇫🇷  {mask_fr.sum():,} lignes France détectées")

    mask_manquant = mask_fr & (
        df[col_tva].isna()
        | df[col_tva].str.strip().isin(["-", "", "nan", "NaN", "N/A", "n/a"])
    )
    n_manquants = mask_manquant.sum()
    print(f"⚠️   {n_manquants:,} TVA manquants à rechercher")

    if n_manquants == 0:
        print("✅ Aucun TVA manquant")
        return df.copy(), [], {}

    cols_uniques = [col_nom]
    if col_cp:    cols_uniques.append(col_cp)
    if col_ville: cols_uniques.append(col_ville)

    benef_uniques = (
        df.loc[mask_manquant, cols_uniques]
          .drop_duplicates(subset=[col_nom])
          .reset_index(drop=True)
    )
    n_uniques = len(benef_uniques)
    print(f"📋 {n_uniques:,} bénéficiaires uniques à interroger")
    duree_min = int(n_uniques * DELAI_API * 1.2)
    duree_max = int(n_uniques * DELAI_API * 5)
    print(f"⏱️   Durée estimée : {duree_min}s – {duree_max}s\n")

    session = requests.Session()
    session.headers.update({"User-Agent": "FTS-TVA-Recherche/2.0"})

    rapport, cache = [], {}

    for _, row in tqdm(benef_uniques.iterrows(), total=n_uniques, desc="Recherche TVA"):
        nom   = str(row[col_nom]).strip()
        cp    = str(row[col_cp]).strip()    if col_cp    and pd.notna(row.get(col_cp))    else None
        ville = str(row[col_ville]).strip() if col_ville and pd.notna(row.get(col_ville)) else None

        res = rechercher_tva(nom, ville, cp, session, seuil)
        cache[nom] = res

        rapport.append({
            "Nom_FTS":      nom,
            "Statut":       res["statut"],
            "Strategie":    res["strategie"],
            "SIREN":        res["siren"],
            "TVA_Trouvee":  res["tva"],
            "Nom_API":      res["nom_api"],
            "Score":        res["score"],
            "Detail_Score": res.get("detail", ""),   # audit des 5 critères
        })

    df_out = df.copy()
    updated_rows = {}

    for idx in df_out[mask_manquant].index:
        nom = str(df_out.at[idx, col_nom]).strip()
        res = cache.get(nom)
        if res and res["statut"] == "TROUVE" and res["tva"]:
            df_out.at[idx, col_tva] = res["tva"]
            updated_rows[idx] = res["score"]

    n_trouves = len(updated_rows)
    taux = n_trouves / n_manquants * 100 if n_manquants > 0 else 0
    print(f"\n🎯 {n_trouves:,} / {n_manquants:,} TVA retrouvés ({taux:.1f}%)")
    n_haute = sum(1 for s in updated_rows.values() if s >= SEUIL_HAUTE_CONF)
    print(f"   🟢 Haute confiance (≥{SEUIL_HAUTE_CONF}) : {n_haute:,}")
    print(f"   🟡 Confiance moyenne ({seuil}–{SEUIL_HAUTE_CONF-1}) : {n_trouves - n_haute:,}")

    return df_out, rapport, updated_rows


