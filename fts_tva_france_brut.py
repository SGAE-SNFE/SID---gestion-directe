def exporter_excel_colore(df: pd.DataFrame, updated_rows: dict, nom_fichier: str) -> None:
    print(f"📊 Export Excel : {nom_fichier} ({len(df):,} lignes)...")
    df.to_excel(nom_fichier, index=False, sheet_name="DATASET", engine="openpyxl")

    wb = load_workbook(nom_fichier)
    ws = wb.active
    ws.title = "DATASET"

    col_tva_nom = next((c for c in df.columns if "vat" in c.lower() or "tva" in c.lower()), None)
    col_tva_idx = list(df.columns).index(col_tva_nom) + 1 if col_tva_nom else None

    fill_verte  = PatternFill(start_color=COULEUR_LIGNE_VERTE, fill_type="solid")
    fill_jaune  = PatternFill(start_color=COULEUR_LIGNE_JAUNE, fill_type="solid")
    fill_cv     = PatternFill(start_color=COULEUR_CELL_VERTE,  fill_type="solid")
    fill_co     = PatternFill(start_color=COULEUR_CELL_ORANGE, fill_type="solid")
    font_blanc  = Font(bold=True, color="FFFFFF")
    n_cols = len(df.columns)

    for idx, score in updated_rows.items():
        row_excel = idx + 2
        haute = score >= SEUIL_HAUTE_CONF
        fill  = fill_verte if haute else fill_jaune
        for c in range(1, n_cols + 1):
            ws.cell(row=row_excel, column=c).fill = fill
        if col_tva_idx:
            cell = ws.cell(row=row_excel, column=col_tva_idx)
            cell.fill = fill_cv if haute else fill_co
            cell.font = font_blanc

    if col_tva_idx:
        hdr = ws.cell(row=1, column=col_tva_idx)
        hdr.fill = PatternFill(start_color="4472C4", fill_type="solid")
        hdr.font = Font(bold=True, color="FFFFFF")

    ws.freeze_panes = "A2"
    ws.auto_filter.ref = ws.dimensions
    wb.save(nom_fichier)
    print(f"   ✅ {len(updated_rows):,} lignes colorées → {nom_fichier}")


def _col_lettre(n: int) -> str:
    s = ""
    while n > 0:
        n, r = divmod(n - 1, 26)
        s = chr(65 + r) + s
    return s


def generer_rapport(rapport: list, nom_fichier: str) -> None:
    if not rapport:
        print("⚠️  Rapport vide")
        return

    print(f"📋 Génération rapport : {nom_fichier}...")
    df_rap = pd.DataFrame(rapport)

    with pd.ExcelWriter(nom_fichier, engine="xlsxwriter") as writer:
        df_rap.to_excel(writer, index=False, sheet_name="Résultats_TVA")
        wb = writer.book
        ws = writer.sheets["Résultats_TVA"]
        n = len(df_rap)

        fmt_hdr    = wb.add_format({"bold": True, "bg_color": "#4472C4",
                                    "font_color": "#FFFFFF", "border": 1,
                                    "text_wrap": True, "valign": "vcenter"})
        fmt_trouve = wb.add_format({"bg_color": "#C6EFCE"})
        fmt_non    = wb.add_format({"bg_color": "#FFC7CE"})
        fmt_exclu  = wb.add_format({"bg_color": "#D9D9D9"})

        for i, col in enumerate(df_rap.columns):
            ws.write(0, i, col, fmt_hdr)

        idx_statut     = list(df_rap.columns).index("Statut")
        lettre_statut  = _col_lettre(idx_statut + 1)
        n_cols = len(df_rap.columns) - 1

        for statut, fmt in [("TROUVE", fmt_trouve), ("NON_TROUVE", fmt_non), ("EXCLU", fmt_exclu)]:
            ws.conditional_format(1, 0, n, n_cols, {
                "type": "formula",
                "criteria": f'=${lettre_statut}2="{statut}"',
                "format": fmt,
            })

        ws.set_row(0, 30)
        ws.freeze_panes(1, 0)
        ws.autofilter(0, 0, n, n_cols)
        ws.set_column(0, 0, 60)   # Nom_FTS
        ws.set_column(1, 1, 14)   # Statut
        ws.set_column(2, 2, 26)   # Strategie
        ws.set_column(3, 3, 14)   # SIREN
        ws.set_column(4, 4, 18)   # TVA_Trouvee
        ws.set_column(5, 5, 50)   # Nom_API
        ws.set_column(6, 6, 8)    # Score
        ws.set_column(7, 7, 80)   # Detail_Score — audit des 5 critères

        # Onglet résumé
        resume_statut = df_rap["Statut"].value_counts().reset_index()
        resume_statut.columns = ["Statut", "Nombre"]
        resume_statut["Taux (%)"] = (resume_statut["Nombre"] / len(df_rap) * 100).round(1)

        resume_strat = (
            df_rap[df_rap["Statut"] == "TROUVE"]["Strategie"]
            .value_counts().reset_index()
        )
        if not resume_strat.empty:
            resume_strat.columns = ["Stratégie gagnante", "Nombre"]

        resume_statut.to_excel(writer, index=False, sheet_name="Résumé", startrow=0)
        if not resume_strat.empty:
            resume_strat.to_excel(writer, index=False, sheet_name="Résumé",
                                  startrow=len(resume_statut) + 3)

        ws_res = writer.sheets["Résumé"]
        ws_res.set_column(0, 0, 30)
        ws_res.set_column(1, 2, 15)

    print(f"   ✅ Rapport : {len(df_rap)} bénéficiaires — {nom_fichier}")
    print()
    print("  Résumé par statut :")
    for _, row in resume_statut.iterrows():
        print(f"   {row['Statut']:15s} : {int(row['Nombre']):4d}  ({row['Taux (%)']:.1f}%)")
    if not resume_strat.empty:
        print()
        print("  TVA trouvés par stratégie :")
        for _, row in resume_strat.iterrows():
            print(f"   {row['Stratégie gagnante']:26s} : {int(row['Nombre']):4d}")


